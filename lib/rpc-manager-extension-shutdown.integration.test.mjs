import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { createJiti } from "jiti";
const root = await mkdtemp(join(tmpdir(), "pi-web-exit-reopen-"));
const keys = ["HOME", "PI_CODING_AGENT_DIR", "PI_OFFLINE"];
const saved = keys.map((key) => process.env[key]);
process.env.HOME = root; process.env.PI_CODING_AGENT_DIR = root; process.env.PI_OFFLINE = "1";
const { startRpcSession } = await createJiti(import.meta.url).import("./rpc-manager.ts");
test.after(async () => {
  keys.forEach((key, i) => { if (saved[i] === undefined) delete process.env[key]; else process.env[key] = saved[i]; });
  await rm(root, { recursive: true, force: true });
});
test("a retained file can be reopened normally after extension exit, without a session-id barrier", async (t) => {
  const { session, realSessionId } = await startRpcSession("__new__reopen", "", root, { toolNames: [] });
  t.after(() => session.shutdown());
  session.inner.sessionManager.appendMessage({ role: "user", content: "persisted", timestamp: 1 });
  const path = session.sessionFile;
  const bind = session.inner.bindExtensions;
  let request;
  session.inner.bindExtensions = async function (bindings) { request = bindings.shutdownHandler; await bind.call(this, bindings); };
  session.beginExtensionBinding(); await session.waitUntilReady();
  request();
  assert.equal(await session.waitUntilDisposed(2000), true);
  const next = await startRpcSession(realSessionId, path);
  t.after(() => next.session.shutdown());
  assert.notEqual(next.session, session);
  assert.equal(next.realSessionId, realSessionId);
  assert.equal(next.session.isAlive(), true);
});
