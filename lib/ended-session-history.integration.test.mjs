import assert from "node:assert/strict";
import { mkdtemp, mkdir, rm } from "node:fs/promises";
import { join } from "node:path";
import { tmpdir } from "node:os";
import test from "node:test";
import { SessionManager } from "@earendil-works/pi-coding-agent";
import { createJiti } from "jiti";
const root = await mkdtemp(join(tmpdir(), "pi-web-ended-history-"));
const keys = ["HOME", "PI_CODING_AGENT_DIR", "PI_OFFLINE"];
const saved = keys.map((key) => process.env[key]);
process.env.HOME = root; process.env.PI_CODING_AGENT_DIR = root; process.env.PI_OFFLINE = "1";
const jiti = createJiti(import.meta.url, { tsconfigPaths: true });
const { GET } = await jiti.import("../app/api/sessions/[id]/route.ts");
const { cacheSessionPath } = await jiti.import("./session-reader.ts");
test.after(async () => {
  keys.forEach((key, index) => { if (saved[index] === undefined) delete process.env[key]; else process.env[key] = saved[index]; });
  await rm(root, { recursive: true, force: true });
});
test("the final history GET reads saved custom entries without registering or starting a runtime", async () => {
  const dir = join(root, "sessions"); await mkdir(dir);
  const manager = SessionManager.create(root, dir);
  const user = manager.appendMessage({ role: "user", content: "saved question", timestamp: 1 });
  const final = manager.appendCustomMessageEntry("shutdown-note", "final persisted message", true, { final: true });
  const id = manager.getSessionId();
  cacheSessionPath(id, manager.getSessionFile());
  const get = () => GET(new Request(`http://test/api/sessions/${id}?deferThinking=1&deferMedia=1&anchor=${user}`), { params: Promise.resolve({ id }) });
  const response = await get();
  assert.equal(response.status, 200);
  const data = await response.json();
  assert.deepEqual(data.context.entryIds, [user, final]);
  assert.equal(data.context.messages.at(-1).content, "final persisted message");
  assert.equal(globalThis.__piSessions?.has(id) ?? false, false);
  assert.equal(globalThis.__piStartLocks?.has(id) ?? false, false);
  await rm(manager.getSessionFile());
  assert.equal((await get()).status, 404);
  assert.equal(globalThis.__piSessions?.has(id) ?? false, false);
});
