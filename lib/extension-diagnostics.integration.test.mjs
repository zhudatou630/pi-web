import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { createJiti } from "jiti";
const root = await mkdtemp(join(tmpdir(), "pi-web-extension-diagnostics-"));
const keys = ["HOME", "PI_CODING_AGENT_DIR", "PI_OFFLINE"];
const saved = keys.map((key) => process.env[key]);
process.env.HOME = root;
process.env.PI_CODING_AGENT_DIR = root;
process.env.PI_OFFLINE = "1";
const { startRpcSession } = await createJiti(import.meta.url).import("./rpc-manager.ts");
test.after(async () => {
  keys.forEach((key, i) => { if (saved[i] === undefined) delete process.env[key]; else process.env[key] = saved[i]; });
  await rm(root, { recursive: true, force: true });
});
test("real SDK loader and session_start failures reach every page and refresh after reload", async (t) => {
  const dir = join(root, "extensions"); await mkdir(dir);
  await writeFile(join(dir, "broken.js"), "export default function () { syntax error");
  await writeFile(join(dir, "throws.js"), 'export default function(pi) { pi.on("session_start", () => { throw new Error("start boom"); }); }');
  const { session } = await startRpcSession(`__new__${randomUUID()}`, "", root);
  t.after(() => session.shutdown());
  const heard = () => { const out = []; session.onEvent((event) => out.push(event))(); return out; };
  const first = heard();
  assert.ok(first.some((event) => event.error === "start boom"));
  assert.ok(first.some((event) => /broken\.js/.test(event.message ?? "")));
  assert.deepEqual(heard(), first);
  await writeFile(join(dir, "broken.js"), "export default function () {}");
  await session.send({ type: "reload" });
  assert.ok(!heard().some((event) => /broken\.js/.test(event.message ?? "")));
  assert.ok(heard().some((event) => event.error === "start boom"));
});
